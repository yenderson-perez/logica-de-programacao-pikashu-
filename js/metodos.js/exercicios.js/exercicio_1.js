//1 Crie um objeto calculadora com metodos somar, subtrair, multiplicar e dividir.
let calculadora = {

     somar(valorA, valorB){
       return valorA + valorB;
    },  
     subtrair(valorA, valorB){
        return valorA - valorB;
    },
     multiplicar(valorA, valorB){
        return valorA * valorB;
     },
     dividir(valorA, valorB){
        return valorA / valorB;
}
}
console.log(calculadora.somar(5, 10),
calculadora.subtrair(5, 10),
calculadora.multiplicar(5, 10),
calculadora.dividir(5, 10)
);











